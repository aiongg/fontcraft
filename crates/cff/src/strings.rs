//! The standard strings and the predefined charsets of the CFF specification (Adobe Technical
//! Note #5176, appendices A and C), and the String INDEX a font builds on top of them.
//!
//! The tables are data from the public specification. They were transcribed from fontTools'
//! `cffLib` (MIT, Copyright (c) 2017 Just van Rossum and contributors), which reproduces them.

use std::collections::HashMap;

use crate::Error;

/// Number of standard strings: SIDs below this name a standard string.
pub(crate) const STANDARD_COUNT: usize = 391;
/// Number of glyphs in the predefined ISOAdobe charset (SIDs 0 to 228, in order).
pub(crate) const ISO_ADOBE_COUNT: usize = 229;
/// Highest SID a font can use: SIDs are 16-bit.
const MAX_SID: usize = 65_535;

/// SID allocation for one font, in the order the strings are first asked for.
pub(crate) struct Strings {
    standard: HashMap<&'static [u8], u16>,
    custom: Vec<Vec<u8>>,
    custom_ids: HashMap<Vec<u8>, u16>,
}

impl Strings {
    pub(crate) fn new() -> Self {
        let mut standard = HashMap::with_capacity(STANDARD_COUNT);
        for (sid, s) in (0u16..).zip(STANDARD_STRINGS.iter()) {
            standard.insert(s.as_bytes(), sid);
        }
        Self { standard, custom: Vec::new(), custom_ids: HashMap::new() }
    }

    /// The SID of `s`: its standard SID, the SID it was given before, or a new one.
    pub(crate) fn sid(&mut self, s: &[u8]) -> Result<u16, Error> {
        if let Some(&sid) = self.standard.get(s) {
            return Ok(sid);
        }
        if let Some(&sid) = self.custom_ids.get(s) {
            return Ok(sid);
        }
        let next = STANDARD_COUNT + self.custom.len();
        let sid = u16::try_from(next).ok().filter(|_| next <= MAX_SID).ok_or(Error::TooManyStrings)?;
        self.custom.push(s.to_vec());
        self.custom_ids.insert(s.to_vec(), sid);
        Ok(sid)
    }

    /// The strings that are not standard, in SID order: the items of the String INDEX.
    pub(crate) fn custom(&self) -> &[Vec<u8>] {
        &self.custom
    }
}

