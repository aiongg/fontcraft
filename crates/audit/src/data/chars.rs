pub const MIN_CJK_GLYPHS: usize = 150;

/// U+25CC DOTTED CIRCLE, the base shapers show under a mark that has none.
pub const DOTTED_CIRCLE: u32 = 0x25CC;

pub fn is_whitespace(cp: u32) -> bool {
    WHITESPACE.contains(&cp)
}

/// Whether a glyph for `cp` must have no outline: whitespace (except the Ogham space mark)
/// and the invisible characters.
pub fn must_be_empty(cp: u32) -> bool {
    cp != OGHAM_SPACE_MARK && (WHITESPACE.contains(&cp) || INVISIBLE.contains(&cp))
}

pub fn is_cjk(cp: u32) -> bool {
    CJK_RANGES.iter().any(|(first, last)| (*first..=*last).contains(&cp))
}

pub fn is_arabic_spacing_symbol(cp: u32) -> bool {
    (ARABIC_SPACING_SYMBOLS.0..=ARABIC_SPACING_SYMBOLS.1).contains(&cp)
}

pub fn is_soft_dotted(cp: u32) -> bool {
    SOFT_DOTTED.binary_search(&cp).is_ok()
}

pub fn is_math_sign(cp: u32) -> bool {
    MATH_SIGNS.binary_search(&cp).is_ok()
}

