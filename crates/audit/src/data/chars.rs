#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_answer_known_characters() {
        assert!(must_be_empty(0x0020));
        assert!(must_be_empty(0x200B));
        assert!(!must_be_empty(0x1680));
        assert!(!must_be_empty(0x0041));
        assert!(is_cjk(0x4E00));
        assert!(!is_cjk(0x3000));
        assert!(is_arabic_spacing_symbol(0xFBC2));
        assert!(!is_arabic_spacing_symbol(0xFBC3));
        assert!(is_soft_dotted(0x0069));
        assert!(is_soft_dotted(0x1DF1A));
        assert!(!is_soft_dotted(0x0131));
        assert!(is_math_sign(0x2212));
        assert!(is_math_sign(0x3012));
        assert!(!is_math_sign(0x0041));
        for list in [CASE_MAPPING_EXCEPTIONS, WHITESPACE, LEGACY_ACCENTS, INDIC_LETTERS, SOFT_DOTTED, MATH_SIGNS] {
            assert!(list.windows(2).all(|w| matches!(w, [a, b] if a < b)));
        }
        assert!(SOFT_DOTTED_SEQUENCES.iter().all(|s| s.first().is_some_and(|cp| is_soft_dotted(*cp))));
    }
}
