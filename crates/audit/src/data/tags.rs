#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn registered_tags_are_found_and_sorted() {
        assert_eq!(script_name(*b"latn"), Some("Latin"));
        assert_eq!(script_name(*b"DFLT"), Some("Default"));
        assert!(is_registered_script(*b"dev2"));
        assert!(!is_registered_script(*b"latx"));
        assert!(is_registered_language(*b"TRK "));
        assert!(!is_registered_language(*b"TUR "));
        assert_eq!(language_slip(*b"TUR "), Some(*b"TRK "));
        assert!(is_registered_feature(*b"liga"));
        assert!(is_registered_feature(*b"ss20"));
        assert!(is_registered_feature(*b"cv99"));
        assert!(!is_registered_feature(*b"ss21"));
        assert!(is_deprecated_feature(*b"size"));
        assert!(is_registered_baseline(*b"romn"));
        assert!(is_registered_axis(*b"opsz"));
        for list in [SCRIPTS, LANGUAGES, FEATURES] {
            assert!(list.windows(2).all(|w| matches!(w, [a, b] if a.0 < b.0)));
        }
    }

    #[test]
    fn private_feature_tags_are_uppercase_letters() {
        assert!(is_private_feature(*b"HARF"));
        assert!(is_private_feature(*b"AB  "));
        assert!(!is_private_feature(*b"Abcd"));
        assert!(!is_private_feature(*b"AB1 "));
        assert!(!is_private_feature(*b"A B "));
        assert!(!is_private_feature(*b"    "));
        assert_eq!(tag_text(*b"TRK "), "TRK ");
    }
}
