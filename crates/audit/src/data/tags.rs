//! Registered OpenType tags: scripts, language systems, features, baselines and variation axes.
//!
//! Source: the OpenType specification's tag registry pages (Microsoft Typography), as the
//! opentypespec package 1.9.2 types them (https://github.com/simoncozens/opentypespec-py,
//! Apache License 2.0). Tags and names are facts of the registry. The baseline and axis tags
//! are typed here from the registry pages. The deprecated feature tags and the
//! TUR/TRK slip follow FontBakery 1.1.0 (https://github.com/fonttools/fontbakery, Apache License
//! 2.0), `opentype/layout_valid_feature_tags` and comparefamily's family test 12.
//!
//! Tags are the four bytes as stored in the font, space-padded (`b"TRK "`).

/// Feature tags the registry still lists but marks as deprecated.
pub const DEPRECATED_FEATURES: &[[u8; 4]] = &[*b"hngl", *b"opbd", *b"size"];

/// Registered baseline tags (the BASE table's tag list).
pub const BASELINES: &[([u8; 4], &str)] = &[
    (*b"hang", "Hanging baseline"),
    (*b"icfb", "Ideographic character face bottom edge"),
    (*b"icft", "Ideographic character face top edge"),
    (*b"ideo", "Ideographic em-box bottom edge"),
    (*b"idtp", "Ideographic em-box top edge"),
    (*b"math", "Mathematical centre"),
    (*b"romn", "Alphabetic baseline"),
];

/// Registered design-variation axis tags.
pub const AXES: &[([u8; 4], &str)] =
    &[(*b"ital", "Italic"), (*b"opsz", "Optical size"), (*b"slnt", "Slant"), (*b"wdth", "Width"), (*b"wght", "Weight")];

/// Language-system tags that are often written for another language by mistake: (the tag found,
/// the tag meant). `TUR ` is not registered; Turkish is `TRK `.
pub const LANGUAGE_SLIPS: &[([u8; 4], [u8; 4])] = &[(*b"TUR ", *b"TRK ")];

fn find(list: &'static [([u8; 4], &'static str)], tag: [u8; 4]) -> Option<&'static str> {
    list.binary_search_by(|(t, _)| t.cmp(&tag)).ok().and_then(|i| list.get(i)).map(|(_, name)| *name)
}

/// The registered name of a script tag (`DFLT` included).
pub fn script_name(tag: [u8; 4]) -> Option<&'static str> {
    find(SCRIPTS, tag)
}

pub fn is_registered_script(tag: [u8; 4]) -> bool {
    script_name(tag).is_some()
}

/// The registered name of a language-system tag. `dflt` is not a language-system tag: the
/// default language system has no tag record.
pub fn language_name(tag: [u8; 4]) -> Option<&'static str> {
    find(LANGUAGES, tag)
}

pub fn is_registered_language(tag: [u8; 4]) -> bool {
    language_name(tag).is_some()
}

/// The registered name of a feature tag; `cv01`–`cv99` and `ss01`–`ss20` are registered one by
/// one.
pub fn feature_name(tag: [u8; 4]) -> Option<&'static str> {
    find(FEATURES, tag)
}

pub fn is_registered_feature(tag: [u8; 4]) -> bool {
    feature_name(tag).is_some()
}

pub fn is_deprecated_feature(tag: [u8; 4]) -> bool {
    DEPRECATED_FEATURES.contains(&tag)
}

/// A private feature tag: one to four uppercase letters A–Z, padded with spaces at the end.
pub fn is_private_feature(tag: [u8; 4]) -> bool {
    let letters = tag.iter().take_while(|b| b.is_ascii_uppercase()).count();
    letters > 0 && tag.iter().skip(letters).all(|b| *b == b' ')
}

pub fn baseline_name(tag: [u8; 4]) -> Option<&'static str> {
    BASELINES.iter().find(|(t, _)| *t == tag).map(|(_, name)| *name)
}

pub fn is_registered_baseline(tag: [u8; 4]) -> bool {
    baseline_name(tag).is_some()
}

pub fn axis_name(tag: [u8; 4]) -> Option<&'static str> {
    AXES.iter().find(|(t, _)| *t == tag).map(|(_, name)| *name)
}

pub fn is_registered_axis(tag: [u8; 4]) -> bool {
    axis_name(tag).is_some()
}

/// The registered tag a mistyped language-system tag stands for.
pub fn language_slip(tag: [u8; 4]) -> Option<[u8; 4]> {
    LANGUAGE_SLIPS.iter().find(|(found, _)| *found == tag).map(|(_, meant)| *meant)
}

/// A tag as text for messages, with its padding kept (`'TRK '`).
pub fn tag_text(tag: [u8; 4]) -> String {
    tag.iter().map(|b| if b.is_ascii_graphic() || *b == b' ' { char::from(*b) } else { '?' }).collect()
}

