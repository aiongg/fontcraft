//! The code page bits of the OS/2 table (`ulCodePageRange1`–`2`): what each bit names, and a
//! coverage rule for the bits a character set earns.
//!
//! The bit assignments and names are those of the OpenType specification's OS/2 page. The
//! coverage rule is ours, written from the code pages' published character repertoires:
//!
//! - a single-byte code page (bits 0–8, 16, 29, 48–63) is covered when the font maps every
//!   printable ASCII character and every letter of the code page's upper half (bytes 0x80 to
//!   0xFF whose character is in a Unicode letter category);
//! - code page 932 (bit 17) when it maps every kana of JIS X 0208;
//! - 936 and 950 (bits 18 and 20) when it maps twenty common ideographs whose simplified form
//!   is only in GB 2312 or whose traditional form is only in Big5;
//! - 949 (bit 19) when it maps the 2,350 Hangul syllables of KS X 1001, and 1361 (bit 21) when
//!   it maps all 11,172;
//! - the OEM and Symbol bits (30, 31) are never earned by coverage.
//!
//! The repertoires were read from the Unicode mapping tables of each code page as Python 3.12's
//! codecs carry them (ISO 8859-6 stands for ASMO 708). Compilers use other rules for the same
//! bits, so a check that compares stored bits with this rule reports a difference, not an error.

