/// The code page bits of the CJK code pages (932, 936, 949, 950, 1361).
pub const CJK_BITS: &[u8] = &[17, 18, 19, 20, 21];

/// First and last Hangul syllable (U+AC00 to U+D7A3, 11,172 syllables).
pub const HANGUL_SYLLABLES: (u32, u32) = (0xAC00, 0xD7A3);

/// The two OS/2 fields as one value, `ulCodePageRange1` in the low 32 bits.
pub fn from_fields(r1: u32, r2: u32) -> u64 {
    u64::from(r1) | u64::from(r2) << 32
}

/// (code page number or 0, name) of an assigned bit.
pub fn code_page(bit: u8) -> Option<(u16, &'static str)> {
    CODE_PAGES.iter().find(|(b, _, _)| *b == bit).map(|(_, number, name)| (*number, *name))
}

/// Whether `cp` is one of the 2,350 Hangul syllables of KS X 1001, the modern syllables that
/// Korean fonts are expected to draw.
pub fn is_ks_x_1001_hangul(cp: u32) -> bool {
    let Some(offset) = cp.checked_sub(HANGUL_SYLLABLES.0).filter(|_| cp <= HANGUL_SYLLABLES.1) else {
        return false;
    };
    let word = KS_X_1001_HANGUL.get((offset / 64) as usize).copied().unwrap_or(0);
    word & (1u64 << (offset % 64)) != 0
}

/// The code page bits a font that maps the code points `has` accepts earns under the rule in
/// the module documentation, bit `n` of the result for code page bit `n`.
pub fn bits_for(has: impl Fn(u32) -> bool) -> u64 {
    let ascii = (0x20..=0x7E).all(&has);
    let all = |list: &[u16]| list.iter().all(|cp| has(u32::from(*cp)));
    let mut bits = 0u64;
    if ascii {
        for (bit, letters) in SINGLE_BYTE_LETTERS {
            if all(letters) {
                bits |= 1u64 << bit;
            }
        }
    }
    if all(KANA) {
        bits |= 1 << 17;
    }
    if all(SIMPLIFIED) {
        bits |= 1 << 18;
    }
    if all(TRADITIONAL) {
        bits |= 1 << 20;
    }
    let (first, last) = HANGUL_SYLLABLES;
    if (first..=last).filter(|cp| is_ks_x_1001_hangul(*cp)).all(&has) {
        bits |= 1 << 19;
    }
    if (first..=last).all(&has) {
        bits |= 1 << 21;
    }
    bits
}

