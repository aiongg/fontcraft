//! Expected contour counts of encoded glyphs, for `check.outlines.contourCount`.
//!
//! Ported from FontBakery 1.1.0 (https://github.com/fonttools/fontbakery, Apache License 2.0),
//! `fontbakery/glyphdata.py` (`desired_glyph_data`), the table its `contour_count` check reads:
//! for each code point, every contour count seen in a set of well-made static fonts. Private-use
//! code points are left out, as that check leaves them out; where the table lists a code point
//! twice, the later entry is kept, as the check's dictionary keeps it.

/// The contour counts a glyph for `cp` is expected to have, or `None` when the table has no
/// entry (private-use code points never have one).
pub fn expected_contours(cp: u32) -> Option<&'static [u8]> {
    let i = EXPECTED.binary_search_by(|(c, _)| c.cmp(&cp)).ok()?;
    EXPECTED.get(i).map(|(_, counts)| *counts)
}

/// Whether `cp` is in a private use area (U+E000–F8FF, planes 15 and 16).
pub fn is_private_use(cp: u32) -> bool {
    (0xE000..=0xF8FF).contains(&cp) || (0xF0000..=0xFFFFD).contains(&cp) || (0x100000..=0x10FFFD).contains(&cp)
}

