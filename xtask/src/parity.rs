//! `cargo xtask parity`: what of the inventory exists.
//!
//! A command row counts as **live** when its id is in the engine's registry or the shell's UI
//! command table. Every registered command must have an inventory row, so a feature is specified
//! before (or with) its code. Live means "exists", not "behaves like the reference": behaviour is
//! graded by hand in ROADMAP.md.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::Path;

use crate::spec::{self, Inventory, KINDS};

pub fn live_ids() -> BTreeSet<&'static str> {
    fontcraft_engine::command_specs().iter().map(|c| c.id).chain(fontcraft_ui_egui::UI_COMMANDS.iter().map(|c| c.0)).collect()
}

fn pct(done: usize, total: usize) -> String {
    if total == 0 { "–".into() } else { format!("{:.1}%", 100.0 * done as f64 / total as f64) }
}

pub fn render(inv: &Inventory, live: &BTreeSet<&'static str>) -> String {
    let count = |kind: &str, pred: &dyn Fn(&spec::Row) -> bool| inv.rows.iter().filter(|r| r.kind == kind && pred(r)).count();
    let is_live = |r: &spec::Row| live.contains(r.key.as_str());
    let commands = count("command", &|_| true);
    let commands_live = count("command", &is_live);
    let mut out = String::new();
    let _ = writeln!(out, "# Parity: inventory against the live command registry\n");
    let _ = writeln!(
        out,
        "Generated by `cargo xtask parity` from `spec/inventory/*.toml`; do not edit. `cargo xtask ci` fails when it is out of date.\n"
    );
    let _ = writeln!(
        out,
        "A command is **live** when its id is registered in the engine or the UI shell. Live means the command exists, not that it behaves like the reference; behaviour is graded in [ROADMAP.md](../ROADMAP.md).\n"
    );
    let _ = writeln!(
        out,
        "**{commands_live} of {commands} commands live ({}).** {} inventory rows in all.\n",
        pct(commands_live, commands),
        inv.rows.len()
    );

    let _ = writeln!(out, "## By area\n");
    let _ = writeln!(out, "| Area | Weight | Commands | Live | Tools | Panels | Behaviours | Other rows |");
    let _ = writeln!(out, "|---|---:|---:|---:|---:|---:|---:|---:|");
    let mut weighted = 0.0;
    let mut weights = 0.0;
    for a in &inv.areas {
        let in_area = |r: &spec::Row| r.area == a.id;
        let (c, l) = (count("command", &in_area), count("command", &|r| in_area(r) && is_live(r)));
        let other: usize = KINDS.iter().filter(|k| !matches!(**k, "command" | "tool" | "panel" | "behavior")).map(|k| count(k, &in_area)).sum();
        if c > 0 {
            weighted += f64::from(a.weight) * l as f64 / c as f64;
            weights += f64::from(a.weight);
        }
        let _ = writeln!(
            out,
            "| {} (`{}`) | {} | {c} | {l} ({}) | {} | {} | {} | {other} |",
            a.title,
            a.id,
            a.weight,
            pct(l, c),
            count("tool", &in_area),
            count("panel", &in_area),
            count("behavior", &in_area)
        );
    }
    let _ = writeln!(
        out,
        "\nWeighted command coverage (Σ weight × live share ÷ Σ weight, over areas that have commands): **{:.1}%**.\n",
        if weights > 0.0 { 100.0 * weighted / weights } else { 0.0 }
    );

    let _ = writeln!(out, "## By milestone\n");
    let _ = writeln!(out, "| Milestone | Commands | Live | Tools | Panels | Behaviours | Parameters | Checks | CLI | Formats | Tables |");
    let _ = writeln!(out, "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|");
    for m in &inv.milestones {
        let here = |r: &spec::Row| r.milestone == m.id;
        let n = |kind: &str| count(kind, &here);
        let (c, l) = (n("command"), count("command", &|r| here(r) && is_live(r)));
        let _ = writeln!(
            out,
            "| {}: {} | {c} | {l} ({}) | {} | {} | {} | {} | {} | {} | {} | {} |",
            m.id,
            m.title,
            pct(l, c),
            n("tool"),
            n("panel"),
            n("behavior"),
            n("parameter"),
            n("check"),
            n("cli"),
            n("format"),
            n("table")
        );
    }

    let _ = writeln!(out, "\n## By source\n");
    let _ = writeln!(
        out,
        "How each row is known. `handbook` and `docs` come from public documentation, `inferred` is our own design, `memory` is recalled and unverified, `observed` was checked against the running reference (the app on our own fonts or in a public tutorial video, or a reference tool's output).\n"
    );
    let _ = writeln!(out, "| Status | Rows |\n|---|---:|");
    for status in ["handbook", "docs", "inferred", "memory", "observed"] {
        let _ = writeln!(out, "| {status} | {} |", inv.rows.iter().filter(|r| r.status == status).count());
    }

    let _ = writeln!(out, "\n## Live commands\n");
    let _ = writeln!(out, "| Command | Label | Milestone | Inventory file |\n|---|---|---|---|");
    for r in inv.rows.iter().filter(|r| r.kind == "command" && is_live(r)) {
        let _ = writeln!(out, "| `{}` | {} | {} | `{}` |", r.key, r.str("label"), r.milestone, r.file);
    }
    out
}

pub fn run(root: &Path, check: bool) -> Result<(), String> {
    let inv = spec::load(root).map_err(|e| format!("{} problem(s) in spec/ (run `cargo xtask spec`)", e.len()))?;
    let live = live_ids();
    let known: BTreeSet<&str> = inv.rows.iter().filter(|r| r.kind == "command").map(|r| r.key.as_str()).collect();
    let unlisted: Vec<&&str> = live.iter().filter(|id| !known.contains(**id)).collect();
    if !unlisted.is_empty() {
        return Err(format!(
            "{} registered command(s) have no row in spec/inventory/*.toml (specify a feature before or with its code): {unlisted:?}",
            unlisted.len()
        ));
    }
    // A UI command must be `kind = "ui"` in the inventory and an engine command `kind = "engine"`.
    let ui: BTreeSet<&str> = fontcraft_ui_egui::UI_COMMANDS.iter().map(|c| c.0).collect();
    let wrong: Vec<String> = inv
        .rows
        .iter()
        .filter(|r| r.kind == "command" && live.contains(r.key.as_str()))
        .filter(|r| (r.str("kind") == "ui") != ui.contains(r.key.as_str()))
        .map(|r| format!("{} (inventory says {})", r.key, r.str("kind")))
        .collect();
    if !wrong.is_empty() {
        return Err(format!("these commands are registered in the engine but marked ui in the inventory, or the other way round: {wrong:?}"));
    }
    // What users see of a live command (label, menu, shortcut) must be what its row says.
    let registered: Vec<(&str, &str, Vec<&str>, &str)> = fontcraft_engine::command_specs()
        .iter()
        .map(|c| (c.id, c.label, c.menu.to_vec(), c.shortcut.unwrap_or("")))
        .chain(fontcraft_ui_egui::UI_COMMANDS.iter().map(|c| (c.0, c.1, c.2.to_vec(), c.3)))
        .collect();
    let mut drift = Vec::new();
    for (id, label, menu, shortcut) in &registered {
        let Some(row) = inv.rows.iter().find(|r| r.kind == "command" && r.key == *id) else { continue };
        let row_menu: Vec<&str> =
            row.fields.get("menu").and_then(|v| v.as_array()).map(|a| a.iter().filter_map(|v| v.as_str()).collect()).unwrap_or_default();
        if row.str("label") != *label {
            drift.push(format!("{id}: label is \"{label}\" in code, \"{}\" in {}", row.str("label"), row.file));
        }
        if row_menu != *menu {
            drift.push(format!("{id}: menu is {menu:?} in code, {row_menu:?} in {}", row.file));
        }
        if row.str("shortcut") != *shortcut {
            drift.push(format!("{id}: shortcut is \"{shortcut}\" in code, \"{}\" in {}", row.str("shortcut"), row.file));
        }
    }
    if !drift.is_empty() {
        for d in &drift {
            eprintln!("  {d}");
        }
        return Err(format!("{} live command(s) differ from their inventory row: change the code or the row so they agree", drift.len()));
    }
    let text = render(&inv, &live);
    let path = root.join("docs/parity.md");
    if check {
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        if current != text {
            return Err("docs/parity.md is out of date: run `cargo xtask parity` and commit the result".into());
        }
        println!("parity: docs/parity.md is up to date");
    } else {
        std::fs::write(&path, &text).map_err(|e| format!("{}: {e}", path.display()))?;
        println!("parity: wrote docs/parity.md");
    }
    let commands = inv.rows.iter().filter(|r| r.kind == "command").count();
    println!("parity: {} of {commands} commands live", inv.rows.iter().filter(|r| r.kind == "command" && live.contains(r.key.as_str())).count());
    Ok(())
}
