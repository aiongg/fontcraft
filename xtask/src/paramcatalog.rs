//! `cargo xtask paramcatalog [--check]`: the custom-parameter catalogue of `crates/fontinfo`.
//!
//! Reads every `[[parameter]]` row of `spec/inventory/*.toml` that is a custom parameter (not the
//! `font.`, `master.` and `instance.` built-in fields), fails on duplicate names, and writes
//! `crates/fontinfo/src/catalog_data.rs`: one `ParamSpec` per row, with the aliases (UFO long
//! names, format 2 singular spellings), the `units` and `repeatable` flags and the summary (or the
//! row's `picker` text where the summary names a vendor). `--check` fails when the file differs.

use std::path::Path;

/// Where the table goes, relative to the workspace root.
pub const OUTPUT: &str = "crates/fontinfo/src/catalog_data.rs";

const HEADER: &str = "\
// Generated by `cargo xtask paramcatalog` from the `[[parameter]]` rows of spec/inventory/*.toml.
// Do not edit by hand.

use crate::catalog::ParamSpec;
";

/// The table's source text.
fn render() -> String {
    // M7.2: one entry per parameter row, sorted by name.
    format!("{HEADER}\npub(crate) static PARAMS: &[ParamSpec] = &[];\n")
}

pub fn run(root: &Path, check: bool) -> Result<(), String> {
    let path = root.join(OUTPUT);
    let text = render();
    if check {
        let current = std::fs::read_to_string(&path).map_err(|e| format!("{OUTPUT}: {e}"))?;
        if current != text {
            return Err(format!("{OUTPUT} is out of date: run `cargo xtask paramcatalog`"));
        }
        return Ok(());
    }
    std::fs::write(&path, text).map_err(|e| format!("{OUTPUT}: {e}"))?;
    println!("wrote {OUTPUT}");
    Ok(())
}
