/// The built-in fields of Font Info, which have `[[parameter]]` rows of their own but are not
/// custom parameters.
fn is_built_in(name: &str) -> bool {
    ["font.", "master.", "instance."].iter().any(|p| name.starts_with(p))
}

/// One catalogue entry, as the generator reads it from a row.
struct Entry {
    name: String,
    aliases: Vec<&'static str>,
    kind: &'static str,
    scopes: String,
    effect: &'static str,
    milestone: String,
    units: bool,
    repeatable: bool,
    choices: Vec<String>,
    names: &'static str,
    summary: String,
}

fn kind(row: &Row) -> Result<&'static str, String> {
    Ok(match row.str("kind") {
        "bool" => "Bool",
        "number" => "Number",
        "string" | "choice" => "String",
        "list" => "List",
        "dict" if row.str("effect") == "naming" => "Localized",
        "dict" => "Dict",
        other => return Err(format!("{}: parameter `{}`: unknown kind `{other}`", row.file, row.key)),
    })
}

/// What the value names in the font, from the row's `names`.
fn names(row: &Row) -> Result<&'static str, String> {
    Ok(match row.str("names") {
        "" => "Nothing",
        "axis" => "Axis",
        "master" => "Master",
        "glyph" => "Glyph",
        other => return Err(format!("{}: parameter `{}`: unknown names `{other}`", row.file, row.key)),
    })
}

fn effect(row: &Row) -> Result<&'static str, String> {
    Ok(match row.str("effect") {
        "table-value" => "TableValue",
        "export-filter" => "ExportFilter",
        "naming" => "Naming",
        "interpolation" => "Interpolation",
        "hinting" => "Hinting",
        "features" => "Features",
        "ui" => "Ui",
        "other" | "" => "Other",
        other => return Err(format!("{}: parameter `{}`: unknown effect `{other}`", row.file, row.key)),
    })
}

fn scopes(row: &Row) -> String {
    let stated: Vec<&str> =
        row.fields.get("scope").and_then(toml::Value::as_array).map(|a| a.iter().filter_map(toml::Value::as_str).collect()).unwrap_or_default();
    let consts: Vec<&str> = ["font", "master", "instance"]
        .iter()
        .zip(["Scopes::FONT", "Scopes::MASTER", "Scopes::INSTANCE"])
        .filter(|(s, _)| stated.contains(s))
        .map(|(_, c)| c)
        .collect();
    match consts.split_first() {
        None => "Scopes::ANY".to_string(),
        Some((first, rest)) => rest.iter().fold((*first).to_string(), |acc, c| format!("{acc}.with({c})")),
    }
}

/// The entries of the inventory, sorted by name, or every problem found.
fn entries(inv: &spec::Inventory) -> Result<Vec<Entry>, Vec<String>> {
    let mut errors = Vec::new();
    let mut out = Vec::new();
    for row in inv.rows.iter().filter(|r| r.kind == "parameter" && !is_built_in(&r.key)) {
        let picker = row.str("picker");
        let summary = if picker.is_empty() { row.str("summary") } else { picker };
        if let Some(term) = crate::brands::find_term(summary) {
            errors.push(format!("{}: parameter `{}`: the summary names a vendor (`{term}`): give the row a `picker` text", row.file, row.key));
        }
        let (kind, effect, names) = match (kind(row), effect(row), names(row)) {
            (Ok(k), Ok(e), Ok(n)) => (k, e, n),
            (k, e, n) => {
                errors.extend(k.err());
                errors.extend(e.err());
                errors.extend(n.err());
                continue;
            }
        };
        out.push(Entry {
            name: row.key.clone(),
            aliases: ALIASES.iter().find(|(n, _)| *n == row.key).map(|(_, a)| a.to_vec()).unwrap_or_default(),
            kind,
            scopes: scopes(row),
            effect,
            milestone: row.milestone.clone(),
            units: UNITS.contains(&row.key.as_str()),
            repeatable: REPEATABLE.contains(&row.key.as_str()),
            choices: row
                .fields
                .get("values")
                .and_then(toml::Value::as_array)
                .map(|a| a.iter().filter_map(toml::Value::as_str).map(str::to_string).collect())
                .unwrap_or_default(),
            names,
            summary: summary.split_whitespace().collect::<Vec<_>>().join(" "),
        });
    }
    // Every spelling names one entry.
    let mut spellings: BTreeMap<&str, &str> = BTreeMap::new();
    for e in &out {
        for s in std::iter::once(e.name.as_str()).chain(e.aliases.iter().copied()) {
            if let Some(first) = spellings.insert(s, &e.name) {
                errors.push(format!("parameter spelling `{s}` names both `{first}` and `{}`", e.name));
            }
        }
    }
    // The lists above may only name rows that exist.
    for name in ALIASES.iter().map(|(n, _)| *n).chain(UNITS.iter().copied()).chain(REPEATABLE.iter().copied()) {
        if !out.iter().any(|e| e.name == name) {
            errors.push(format!("xtask/src/paramcatalog.rs names `{name}`, which has no [[parameter]] row"));
        }
    }
    out.sort_by(|a, b| a.name.to_lowercase().cmp(&b.name.to_lowercase()).then_with(|| a.name.cmp(&b.name)));
    if errors.is_empty() { Ok(out) } else { Err(errors) }
}

/// The table's source text.
fn render(entries: &[Entry]) -> String {
    let mut out = format!("{HEADER}\n#[rustfmt::skip]\npub(crate) static PARAMS: &[ParamSpec] = &[\n");
    for e in entries {
        let aliases: Vec<String> = e.aliases.iter().map(|a| format!("{a:?}")).collect();
        let choices: Vec<String> = e.choices.iter().map(|c| format!("{c:?}")).collect();
        let vendor = std::iter::once(e.name.as_str()).chain(e.aliases.iter().copied()).any(|s| crate::brands::find_term(s).is_some());
        let _ = writeln!(
            out,
            "    ParamSpec {{ name: {:?}, aliases: &[{}], kind: ParamKind::{}, scopes: {}, effect: Effect::{}, milestone: {:?}, units: {}, repeatable: {}, choices: &[{}], names: Names::{}, summary: {:?} }},{}",
            e.name,
            aliases.join(", "),
            e.kind,
            e.scopes,
            e.effect,
            e.milestone,
            e.units,
            e.repeatable,
            choices.join(", "),
            e.names,
            e.summary,
            if vendor { " // brand-ok: the file-format key" } else { "" }
        );
    }
    out.push_str("];\n");
    out
}

pub fn run(root: &Path, check: bool) -> Result<(), String> {
    let inv = spec::load(root).map_err(|e| format!("spec/ does not load:\n  {}", e.join("\n  ")))?;
    let entries = entries(&inv).map_err(|e| format!("{} problem(s):\n  {}", e.len(), e.join("\n  ")))?;
    let path = root.join(OUTPUT);
    let text = render(&entries);
    if check {
        let current = std::fs::read_to_string(&path).map_err(|e| format!("{OUTPUT}: {e}"))?;
        if current != text {
            return Err(format!("{OUTPUT} is out of date: run `cargo xtask paramcatalog`"));
        }
        println!("paramcatalog: {} parameters, up to date", entries.len());
        return Ok(());
    }
    std::fs::write(&path, text).map_err(|e| format!("{OUTPUT}: {e}"))?;
    println!("wrote {OUTPUT} ({} parameters)", entries.len());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_inventory_gives_a_catalogue_without_clashes() {
        let inv = spec::load(&crate::root()).unwrap_or_else(|e| panic!("{}", e.join("\n")));
        let entries = entries(&inv).unwrap_or_else(|e| panic!("{}", e.join("\n")));
        assert!(entries.len() >= 205, "{}", entries.len());
        let find = |n: &str| entries.iter().find(|e| e.name == n).unwrap_or_else(|| panic!("{n}"));
        assert_eq!(find("descriptions").kind, "Localized");
        assert_eq!(find("descriptions").aliases, ["description", "openTypeNameDescription"]);
        assert!(find("typoAscender").units && !find("typoAscender").repeatable);
        assert!(find("Name Table Entry").repeatable);
        assert_eq!(find("Webfont Formats").choices, ["TTF", "EOT", "WOFF", "WOFF2"]);
        assert!(find("typoAscender").choices.is_empty());
        assert_eq!(find("Keep Glyphs").names, "Glyph");
        assert_eq!(find("Axis Mappings").scopes, "Scopes::FONT.with(Scopes::INSTANCE)");
        let text = render(&entries);
        assert!(text.contains("// brand-ok"), "the key with a vendor's name is marked");
        assert!(text.lines().filter(|l| l.contains("ParamSpec {")).count() == entries.len());
    }
}
