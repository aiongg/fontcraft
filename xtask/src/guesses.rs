//! `cargo xtask guesses`: the register of best guesses.
//!
//! A row's `guesses` list holds the choices FontCraft made where no source says what the reference
//! does. This writes them all to `docs/guesses.md`, and fails when a live command whose status is
//! `inferred` or `memory` records none: such a row is a guess by its status, so the guess must be
//! written down.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::Path;

use crate::parity::live_ids;
use crate::spec::{self, Inventory, Row};

/// Statuses that mark a row as our own design or as recalled, so a live command with one of them
/// must say what it guessed.
const GUESSED_STATUSES: &[&str] = &["inferred", "memory"];

/// Live commands whose status says they are a guess but whose row has no `guesses`.
pub fn unrecorded<'a>(inv: &'a Inventory, live: &BTreeSet<&str>) -> Vec<&'a Row> {
    inv.rows
        .iter()
        .filter(|r| r.kind == "command" && live.contains(r.key.as_str()))
        .filter(|r| GUESSED_STATUSES.contains(&r.status.as_str()) && r.guesses().is_empty())
        .collect()
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

pub fn render(inv: &Inventory, live: &BTreeSet<&str>) -> String {
    let with: Vec<&Row> = inv.rows.iter().filter(|r| !r.guesses().is_empty()).collect();
    let is_live = |r: &Row| r.kind == "command" && live.contains(r.key.as_str());
    let entries: usize = with.iter().map(|r| r.guesses().len()).sum();
    let live_rows = with.iter().filter(|r| is_live(r)).count();
    let mut out = String::new();
    let _ = writeln!(out, "# Best guesses\n");
    let _ = writeln!(
        out,
        "Generated by `cargo xtask guesses` from the `guesses` field of `spec/inventory/*.toml`; do not edit. `cargo xtask ci` fails when it is out of date.\n"
    );
    let _ = writeln!(
        out,
        "Each entry is a choice FontCraft made where no written source says what the reference does and nobody has observed it. Revisit an entry when a source or an observation settles it: change the behaviour if it differs, then remove the entry. Behaviour that follows the handbook but is not yet observed is not a guess; the row's `status` and `notes` say so.\n"
    );
    let _ = writeln!(
        out,
        "To add a guess, append a sentence to the row's `guesses` list and run `cargo xtask guesses`. A live command whose status is `inferred` or `memory` must have at least one entry. **Live** is yes when the row is a command registered in the engine or the shell; it is – for other row kinds.\n"
    );
    let _ = writeln!(out, "**{entries} guesses on {} rows ({live_rows} of them live commands).**\n", with.len());

    let mut files: Vec<&str> = with.iter().map(|r| r.file.as_str()).collect();
    files.dedup();
    for file in files {
        let _ = writeln!(out, "## `{}`\n", file.trim_start_matches("spec/inventory/"));
        let _ = writeln!(out, "| Row | Milestone | Status | Live | Guess |\n|---|---|---|---|---|");
        let here = || with.iter().filter(|r| r.file == file);
        // Live commands first, each group in inventory order.
        for r in here().filter(|r| is_live(r)).chain(here().filter(|r| !is_live(r))) {
            let live_cell = match (r.kind, is_live(r)) {
                (_, true) => "yes",
                ("command", false) => "no",
                _ => "–",
            };
            let row = if r.kind == "command" { format!("`{}`", r.key) } else { format!("`{}` ({})", r.key, r.kind) };
            for g in r.guesses() {
                let _ = writeln!(out, "| {row} | {} | {} | {live_cell} | {} |", r.milestone, r.status, cell(g));
            }
        }
        let _ = writeln!(out);
    }
    out
}

pub fn run(root: &Path, check: bool) -> Result<(), String> {
    let inv = spec::load(root).map_err(|e| format!("{} problem(s) in spec/ (run `cargo xtask spec`)", e.len()))?;
    let live = live_ids();
    let missing = unrecorded(&inv, &live);
    if !missing.is_empty() {
        for r in &missing {
            eprintln!("  {}: {} ({})", r.file, r.key, r.status);
        }
        return Err(format!(
            "{} live command(s) with status inferred or memory have no `guesses`: write down what was chosen where no source says",
            missing.len()
        ));
    }
    let text = render(&inv, &live);
    let path = root.join("docs/guesses.md");
    if check {
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        if current != text {
            return Err("docs/guesses.md is out of date: run `cargo xtask guesses` and commit the result".into());
        }
        println!("guesses: docs/guesses.md is up to date");
    } else {
        std::fs::write(&path, &text).map_err(|e| format!("{}: {e}", path.display()))?;
        println!("guesses: wrote docs/guesses.md");
    }
    let rows: Vec<&Row> = inv.rows.iter().filter(|r| !r.guesses().is_empty()).collect();
    println!(
        "guesses: {} entries on {} rows ({} live commands)",
        rows.iter().map(|r| r.guesses().len()).sum::<usize>(),
        rows.len(),
        rows.iter().filter(|r| r.kind == "command" && live.contains(r.key.as_str())).count()
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::spec::{Area, Milestone};

    fn row(kind: &'static str, key: &str, status: &str, guesses: &[&str]) -> Row {
        let mut fields = toml::Table::new();
        if !guesses.is_empty() {
            fields.insert("guesses".into(), toml::Value::Array(guesses.iter().map(|g| toml::Value::String((*g).into())).collect()));
        }
        Row { kind, key: key.into(), file: "spec/inventory/x.toml".into(), area: "a".into(), milestone: "M3".into(), status: status.into(), fields }
    }

    #[test]
    fn a_live_guessed_command_without_guesses_is_reported_and_live_rows_list_first() {
        let inv = Inventory {
            areas: vec![Area { id: "a".into(), title: "A".into(), weight: 1 }],
            milestones: vec![Milestone { id: "M3".into(), title: "M3".into() }],
            rows: vec![
                row("behavior", "rule.one", "handbook", &["Ours | theirs."]),
                row("command", "path.live", "inferred", &["We chose this."]),
                row("command", "path.bare", "memory", &[]),
                row("command", "path.notLive", "inferred", &[]),
                row("command", "path.documented", "handbook", &[]),
            ],
        };
        let live: BTreeSet<&str> = ["path.live", "path.bare", "path.documented"].into_iter().collect();
        let missing: Vec<&str> = unrecorded(&inv, &live).iter().map(|r| r.key.as_str()).collect();
        assert_eq!(missing, ["path.bare"]);
        let text = render(&inv, &live);
        assert!(text.contains("**2 guesses on 2 rows (1 of them live commands).**"), "{text}");
        let first = text.find("`path.live`").unwrap();
        let second = text.find("`rule.one` (behavior)").unwrap();
        assert!(first < second, "{text}");
        assert!(text.contains("| `path.live` | M3 | inferred | yes | We chose this. |"), "{text}");
        assert!(text.contains("| `rule.one` (behavior) | M3 | handbook | – | Ours \\| theirs. |"), "{text}");
    }
}
